function get_Is(k::Matrix; na::Int64=9, nb::Int64=5, nc::Int64=5)
    #initialise array of zeros
    I_abc = zeros(na, nb, nc, length(k[:,1]))

    for α in 0:na-1
        for β in 0:nb-1
            for γ in 0:nc-1
                #println("$α $β $γ")
                if (β == 2 && γ == 4)
                    I_abc[α+1,β+1,γ+1,:] .= -99.
                elseif (β == 3 && γ == 3)
                    I_abc[α+1,β+1,γ+1,:] .= -99.
                elseif (β == 4 && γ == 2)
                    I_abc[α+1,β+1,γ+1,:] .= -99.
                elseif (β == 4 && γ == 4)
                    I_abc[α+1,β+1,γ+1,:] .= -99.
                else
                    I = compute_I_abc(α, β, γ, k)
                    I_abc[α+1,β+1,γ+1,:] .= I
                end
            end
        end
    end

    return I_abc
end

function read_Is_matrix(α, β, γ, Is, ℓ)
    return Is[α+1+ℓ, β+1+ℓ, γ+1+ℓ,:]
