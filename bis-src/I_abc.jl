    if b == 0
        #a0c
        if c == 0 #a00
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven / (1. + a)
        elseif c == 1 #a01
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1 .+ k2 .* μ123) ./ ((2 + a) .* k3)
        elseif c == 2 #a02
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven .* ((1 + a) .* k1.^2 .+ 
                                 2 .* (1 + a) .* k1 .* k2 .* μ123 .+
                                 k2.^2 .* (1 .+ a .* μ123.^2)) ./ 
                   ((1 + a) .* (3 + a) .* k3.^2)
        elseif c == 3 #a03
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1 .+ k2 .* μ123) .* ((2 + a) .* k1.^2 .+
                                                       2 .* (2 + a) .* k1 .* k2 .* μ123 .+
                                                       k2.^2 .* (3 .+ (a - 1) .* μ123.^2)) ./
                   ((2 + a) .* (4 + a) .* k3.^3)
        elseif c == 4 #a04
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven .* ((1 + a) .* (3 + a) .* k1.^4 .+
                                 4 .* (1 + a) .* (3 + a) .* k1.^3 .* k2 .* μ123 .+
                                 4 .* (1 + a) .* k1 .* k2.^3 .* μ123 .* (3 .+ a .* μ123.^2) .+
                                 6 .* k1.^2 .* k2.^2 .* (1 .+ a .+ (1 + a) .* (2 + a) .* μ123.^2) .+
                                 k2.^4 .* (3 .+ 6 .* a .* μ123.^2 + (a - 2) .* a .* μ123.^4)) ./
                   ((1 + a) .* (3 + a) .* (5 + a) .* k3.^4)
        end

    elseif b == 1
        #a1c
        if c == 0 #a10
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* μ123 ./ (2 + a)
        elseif c == 1 #a11
            a_oddeven = (1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* (k2 .+ 
                                       (1 + a) .* k1 .* μ123 .+
                                       a .* k2 .* μ123.^2) ./
                   ((1 + a) .* (3 + a) .* k3)
        elseif c == 2 #a12
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((2 + a) .* k1.^2 .* μ123 .+
                                       k2.^2 .* μ123 .* (3 .+ (a -1) .* μ123.^2) .+
                                       2 .* k1 .* (k2 .+ (1 + a) .* k2 .* μ123.^2)) ./
                   ((2 + a) .* (4 + a) .* k3.^2)
        elseif c == 3 #a13
            a_oddeven = (1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((1 + a) .* (3 + a) .* k1.^3 .* μ123 .+
                                       3 .* (1 + a) .* k1 .* k2.^2 .* μ123 .* (3 .+ a .* μ123.^2) .+
                                       3 .* k1.^2 .* k2 .* (1 .+ a .+ (1 + a) .* (2 + a) .* μ123.^2) .+
                                       k2.^3 .* (3 .+ 6 .* a .* μ123.^2 .+ (a - 2) .* a .* μ123.^4)) ./
                   ((1 + a) .* (3 + a) .* (5 + a) .* k3.^3)
        elseif c == 4 #14
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((2 + a) .* (4 + a) .* k1.^4 .* μ123 .+
                                       4 .* k1.^3 .* k2 .* (2 .+ a .+ (2 + a) .* (3 + a) .* μ123.^2) .+
                                       6 .* (2 + a) .* k1.^2 .* k2.^2 .* μ123 .* (3 .+ (1 + a) .* μ123.^2) .+
                                       4 .* k1 .* k2.^3 .* (3 .+ 6 .* (1 + a) .* μ123.^2 .+ (a^2 - 1) .* μ123.^4) .+
                                       k2.^4 .* μ123 .* (15 .+ (a - 1) .* μ123.^2 .* (10 .+ (a - 3) .* μ123.^2))) ./
                   ((2 + a) .* (4 + a) .* (6 + a) .* k3.^4) 
        end 

    elseif b == 2
        #a2c
        if c == 0 #a20
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven .* (1 .+ a .* μ123.^2) ./ ((1 + a) * (3 + a))
        elseif c == 1 #a21
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1 .+
                                 (1 + a) .* k1 .* μ123.^2 .+
                                 k2 .* μ123 .* (3 .+ ( a - 1) .* μ123.^2)) ./
                   ((2 + a) .* (4 + a) .* k3)
        elseif c == 2 #a22
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1.^2 .* (1 .+ a .+ (1 + a) .* (2 + a) .* μ123.^2) .+
                                 2 .* (1 + a) .* k1 .* k2 .* μ123 .* (3 .+ a .* μ123.^2) .+
                                 k2.^2 .* (3 .+ 6 .* a .* μ123.^2 .+ (a - 2) .* a .* μ123.^4)) ./
                   ((1 + a) .* (3 + a) .* (5 + a) .* k3.^2)
        elseif c == 3 #a23
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1.^3 .* (2 .+ a .+ (2 + a) .* (3 + a) .* μ123.^2) .+
                                 3 .* (2 + a) .* k1.^2 .* k2 .* μ123 .* (3 .+ (1 + a) .*μ123.^2) .+
                                 3 .* k1 .* k2.^2 .* (3 .+ 6 .* (1 + a) .* μ123.^2 + (a.^2 - 1) .* μ123.^4) .+
                                 k2.^3 .* μ123 .* (15 .+ (a - 1) .* μ123.^2 .* (10 .+ (a - 3) .* μ123.^2))) ./
                   ((2 + a) .* (4 + a) .* (6 + a) .* k3.^3)
        elseif c == 4 #a24
            throw(DomainError(c, "we do not have a24, what are you doing freak?"))
        end

    elseif b == 3
        #a3c
        if c == 0 #a30
            a_oddeven =(-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* (μ123 .* (3 .+ (a -1) .* μ123.^2)) ./ ((2 + a) * (4 + a))
        elseif c == 1 #a31
            a_oddeven =(1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((1 + a) .* k1 .* μ123 .* (3 .+ a .* μ123.^2) .+
                                       k2 .* (3 .+ 6 .* a .* μ123.^2 .+ (a - 2) .* a .* μ123.^4)) ./
