        elseif c == 2 #a32
            a_oddeven =(-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((2 + a) .* k1.^2 .* μ123 .* (3 .+ (1 + a) .* μ123.^2) .+
                                       2 .* k1 .* k2 .* (3 .+ 6 .* (1 + a) .* μ123.^2 .+ (a^2 - 1) .* μ123.^4) .+
                                       k2.^2 .* μ123 .* (15 .+ (a -1) .* μ123.^2 .* (10 .+ (a - 3) .* μ123.^2))) ./
                   ((2 + a) .* (4 + a) .* (6 + a) .* k3.^2)
        elseif c == 3 #a33
            throw(DomainError(c, "we do not have a33, what are you doing freak?"))
        elseif c == 4 #a34
            a_oddeven =(-1. + (-1.)^a) * 0.5
            return -1 .* a_oddeven .* ((2 + a) .* (4 + a) .* k1.^4 .* μ123 .* (3 .+ (3 + a) .* μ123.^2) .+
                                       4 .* (2 + a) .* k1.^3 .* k2 .* (3 .+ (3 + a) .* μ123.^2 .* (6 .+ (1 + a) .* μ123.^2)) .+
                                       6 .* (2 + a) .* k1.^2 .* k2.^2 .* μ123 .* (15 .+ 
                                                                                  10 .* (1 + a) .* μ123.^2 .+ 
                                                                                  (a^2 - 1) .* μ123.^4) .+
                                       4 .* k1 .* k2.^3 .* (15 .+ (1 + a) .* μ123.^2 .*
                                                            (45 .+ (a - 1) .* μ123.^2 .*
                                                             (15 .+ (a - 3) .* μ123.^2))) .+
                                       k2.^4 .* μ123 .* (105 .+ (a - 1) .* μ123.^2 .* 
                                                         (105 .+ (a - 3) .* μ123.^2 .*
                                                          (21 .+ (a - 5) .* μ123.^2)))) ./
                   ((2 + a) .* (4 + a) .* (6 + a) .* (8 + a) .* k3.^4)
        end

    elseif b == 4
        #a4c
        if c == 0 #a40
            a_oddeven = (1. + (-1.)^a) * 0.5
            return a_oddeven .* ((a - 2) .* a .* μ123.^4 + 6 .* a .* μ123.^2 .+ 3) ./ ((1 + a) * (3 + a) * (5 + a))
        elseif c == 1 #a41
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* (k1 .* (3 .+ 6 .* (1 + a) .* μ123.^2 .+ (a^2 - 1) .* μ123.^4) .+
                                 k2 .* μ123 .* (15 .+ (a - 1) .* μ123.^2 .* (10 .+ (a - 3) .* μ123.^2))) ./
                   ((2 + a) .* (4 + a) .* (6 + a) .* k3)
        elseif c == 2 #a42
            throw(DomainError(c, "we do not have a42, what are you doing freak?"))
        elseif c == 3 #a43
            a_oddeven = (-1. + (-1.)^a) * 0.5
            return a_oddeven .* ((2 + a) .* k1.^3 .* (3 .+ (3 + a) .* μ123.^2 .* (6 .+ (1 + a) .* μ123.^2)) .+
                                 3 .* (2 + a) .* k1.^2 .* k2 .* μ123 .* (15 .+ 
                                                                         10 .* (1 + a) .* μ123.^2 .+
                                                                         (a^2 - 1) .* μ123.^4) .+
                                 3 .* k1 .* k2.^2 .* (15 .+ (1 + a) .* μ123.^2 .*
