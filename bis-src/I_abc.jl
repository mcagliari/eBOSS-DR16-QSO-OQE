function μij(k1, k2, k3)
    return 0.5 .* (k3.^2 .- k1.^2 .- k2.^2) ./ (k1 .* k2)
end

function compute_I_abc(a::Int64, b::Int64, c::Int64, k::Matrix)

    if b > 4
        throw(DomainError(b, "abc must 0, 1, 2, 3, or 4"))
    elseif c > 4
        throw(DomainError(c, "abc must 0, 1, 2, 3, or 4"))
    end

    k1, k2, k3 = k[:,1], k[:,2], k[:,3]
    μ123 = μij(k1, k2, k3)
    
